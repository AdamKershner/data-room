function stepsFrom(items) {
  return items.map((item) => (typeof item === 'string' ? { text: item } : item))
}

function playbook({
  id,
  title,
  category,
  owner,
  who,
  when,
  description,
  keywords = [],
  notes,
  sections,
  doneWhen,
}) {
  return {
    id,
    title,
    category,
    owner,
    who,
    when,
    description,
    keywords,
    notes,
    format: 'playbook',
    sections: sections.map((section) => ({
      ...section,
      steps: stepsFrom(section.steps),
    })),
    doneWhen,
  }
}

function task({
  id,
  title,
  category,
  owner,
  who,
  when,
  description,
  keywords = [],
  notes,
  steps,
  doneWhen,
}) {
  return {
    id,
    title,
    category,
    owner,
    who,
    when,
    description,
    keywords,
    notes,
    sections: [{ id: 'process', title: 'Process', steps: stepsFrom(steps) }],
    doneWhen,
  }
}

