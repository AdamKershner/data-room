/** @param {string} companyId */
export function getCompanyScale(companyId) {
  return COMPANY_LANDSCAPE_SCALE[companyId] ?? null
}

/** @param {LandscapeScaleEntry} entry */
export function formatUsersLabel(entry) {
  if (!entry) return null
  const bits = [entry.usersMetric, entry.period].filter(Boolean)
  return bits.length ? `${entry.usersScale} (${bits.join('; ')})` : entry.usersScale
}

/** @param {LandscapeScaleEntry} entry */
export function formatRevenueLabel(entry) {
  if (!entry) return null
  return entry.period ? `${entry.revenue} (${entry.period})` : entry.revenue
}

/**
 * Overlay bullets to put at the top of scaleFacts.
 * @param {LandscapeScaleEntry} entry
 * @returns {string[]}
 */
export function formatScaleFacts(entry) {
  if (!entry) return []
  const usersBit = entry.usersMetric
    ? `${entry.usersScale} — ${entry.usersMetric}`
    : entry.usersScale
  return [`Users (${entry.period}): ${usersBit}`, `Revenue (${entry.period}): ${entry.revenue}`]
}

